// Generated IDs keep callers checked without a second, hand-maintained key list.
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { messages as en } from "../../src/locales/en.mjs";
import { messages as nl } from "../../src/locales/nl.mjs";

const ids = Object.keys(en).sort();
assert.deepEqual(Object.keys(nl).sort(), ids, "Both catalogs must contain exactly the same IDs");
writeFileSync(
  new URL("../../src/locales/message-ids.d.ts", import.meta.url),
  `// Generated by i18n:compile from the English PO catalog.\nexport type MsgKey = ${ids.map((id) => JSON.stringify(id)).join(" | ")};\n`,
);
